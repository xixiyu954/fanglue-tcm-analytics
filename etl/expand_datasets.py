def parse_smhb_props(prop_str: str) -> tuple[str, str, str]:
    nature, flavors, tox = "", [], ""
    if not prop_str or pd.isna(prop_str):
        return "", "", ""
    for tok in re.split(r"[,，、\s]+", str(prop_str)):
        tok = tok.strip()
        if not tok:
            continue
        if tok in NATURES and not nature:
            nature = tok
        elif tok in FLAVORS:
            flavors.append(tok)
        elif tok == "微酸涩":
            flavors.extend(["微酸", "微涩"])
        elif tok in TOX_MAP:
            tox = TOX_MAP[tok]
    return nature, "|".join(dict.fromkeys(flavors)), tox


def parse_tcm_skill_herb_doses() -> dict[str, tuple[float, float]]:
    """从 TCM.Skill 16-22 及安全表提取单味药常用剂量范围 (dose_min, dose_max)。"""
    doses: dict[str, tuple[float, float]] = {}
    base = EXT / "tcm_skill"
    dose_pat = re.compile(r"(\d+(?:\.\d+)?)\s*[~～\-—]\s*(\d+(?:\.\d+)?)\s*g")
    # 1. 安全表毒性药剂量
    sec = (base / "安全-配伍妊娠禁忌与毒性药.md").read_text(encoding="utf-8")
    for line in sec.splitlines():
        if line.startswith("|") and not line.startswith("|---"):
            parts = [x.strip() for x in line.strip("|").split("|")]
            if len(parts) >= 3:
                herb = re.sub(r"[（(].*?[）)]", "", parts[0]).strip().strip("*")
                m = dose_pat.search(parts[2])
                if herb and m:
                    doses[herb] = (float(m.group(1)), float(m.group(2)))
    # 2. 各论 16-22
    for fn in sorted(base.glob("1[6-9]-*.md")) + sorted(base.glob("2[0-2]-*.md")):
        txt = fn.read_text(encoding="utf-8")
        cur_herb = None
        for line in txt.splitlines():
            m_h3 = re.match(r"^###\s*★?\s*([\u4e00-\u9fa5]{1,6})\s+", line)
            if m_h3:
                cur_herb = m_h3.group(1)
            elif line.startswith("| **"):
                parts = [x.strip() for x in line.strip("|").split("|")]
                if len(parts) >= 5:
                    h = parts[0].strip("* ")
                    m = dose_pat.search(parts[-1])
                    if h and m and h not in doses:
                        doses[h] = (float(m.group(1)), float(m.group(2)))
            elif line.startswith("- **"):
                m_b = re.match(r"^- \*\*([\u4e00-\u9fa5]{1,6})\*\*", line)
                if m_b:
                    h = m_b.group(1)
                    m = dose_pat.search(line)
                    if m and h not in doses:
                        doses[h] = (float(m.group(1)), float(m.group(2)))
            elif cur_herb and line.startswith("- ") and cur_herb not in doses:
                m = dose_pat.search(line)
                if m:
                    doses[cur_herb] = (float(m.group(1)), float(m.group(2)))
    return doses


def build_herbs_and_aliases() -> tuple[pd.DataFrame, pd.DataFrame]:
    # 备份或读取已有的 97 味手工核对药材（首次运行先缓存一份 seed）
    seed_dir = EXT / "seed_backup"
    seed_dir.mkdir(parents=True, exist_ok=True)
    for fn in ("herbs.csv", "formulas.csv", "formula_herbs.csv", "aliases.csv"):
        if not (seed_dir / fn).exists() and (RAW / fn).exists():
            (seed_dir / fn).write_bytes((RAW / fn).read_bytes())

    seed_herbs = pd.read_csv(seed_dir / "herbs.csv", dtype={"toxicity": str, "pregnancy": str})
    for col in seed_herbs.select_dtypes(include=["object", "string"]):
        seed_herbs[col] = seed_herbs[col].fillna("")
    smhb = pd.read_excel(EXT / "symmap" / "SMHB.xlsx")
    smhb = smhb[smhb["Suppress"] == 0].copy()
    skill_doses = parse_tcm_skill_herb_doses()

    rows: dict[str, dict] = {}
    # 1. 先载入 SymMap v2.0 全部 698 味药典药材
    for r in smhb.itertuples():
        name = str(r.Chinese_name).strip()
        if not name or name == "nan":
            continue
        nature, flavors, tox = parse_smhb_props(r.Properties_Chinese)
        mer = "|".join(x.strip() for x in re.split(r"[,，、\s]+", str(r.Meridians_Chinese)) if x.strip() and x.strip() != "nan")
        cat = str(r.Class_Chinese).strip() if pd.notna(r.Class_Chinese) else "其他"
        dmin, dmax = skill_doses.get(name, (None, None))
        preg = "禁用" if name in PREG_FORBIDDEN else ("慎用" if name in PREG_CAUTION else "")
        rows[name] = {
            "herb": name,
            "category": cat,
            "nature": nature or "平",
            "flavors": flavors or "甘",
            "meridians": mer,
            "toxicity": tox,
            "dose_min": dmin,
            "dose_max": dmax,
            "pregnancy": preg,
            "pinyin": str(r.Pinyin_name).strip() if pd.notna(r.Pinyin_name) else "",
            "latin_name": str(r.Latin_name).split(",")[0].strip() if pd.notna(r.Latin_name) else "",
            "data_source": "SymMap2.0/中国药典",
        }

    # 2. 补充 EXTRA_HERBS（仅填缺失或补全剂量）
    for h, cat, nat, flv, mer, tox, dmin, dmax, preg, py, lat in EXTRA_HERBS:
        if h not in rows:
            rows[h] = {
                "herb": h, "category": cat, "nature": nat, "flavors": flv, "meridians": mer,
                "toxicity": tox, "dose_min": dmin, "dose_max": dmax, "pregnancy": preg,
                "pinyin": py, "latin_name": lat, "data_source": "中药学/中国药典",
            }
        else:
            if pd.isna(rows[h]["dose_max"]) and dmax is not None:
                rows[h]["dose_min"], rows[h]["dose_max"] = dmin, dmax
            if not rows[h]["pregnancy"] and preg:
                rows[h]["pregnancy"] = preg
            if not rows[h]["toxicity"] and tox:
                rows[h]["toxicity"] = tox

    # 3. 用手工核对的 97 味种子药材覆写关键字段（保证原有示例一致）
    for r in seed_herbs.itertuples():
        h = r.herb.strip()
        if h in rows:
            rows[h]["category"] = r.category or rows[h]["category"]
            rows[h]["nature"] = r.nature or rows[h]["nature"]
            rows[h]["flavors"] = r.flavors or rows[h]["flavors"]
            rows[h]["meridians"] = r.meridians or rows[h]["meridians"]
            if r.toxicity:
                rows[h]["toxicity"] = r.toxicity
            if pd.notna(r.dose_max):
                rows[h]["dose_min"] = float(r.dose_min)
                rows[h]["dose_max"] = float(r.dose_max)
            if r.pregnancy:
                rows[h]["pregnancy"] = r.pregnancy
        else:
            rows[h] = {
                "herb": h, "category": r.category, "nature": r.nature, "flavors": r.flavors,
                "meridians": r.meridians, "toxicity": r.toxicity,
                "dose_min": float(r.dose_min) if pd.notna(r.dose_min) else None,
                "dose_max": float(r.dose_max) if pd.notna(r.dose_max) else None,
                "pregnancy": r.pregnancy, "pinyin": "", "latin_name": "", "data_source": "中药学/中国药典",
            }

    herbs_df = pd.DataFrame(rows.values()).sort_values(["category", "herb"]).reset_index(drop=True)
    known = set(herbs_df["herb"])

    # ---------- 构建别名映射表 ----------
    alias_rows: dict[str, tuple[str, str, str]] = {}
    # a) 原始种子别名
    seed_alias = pd.read_csv(seed_dir / "aliases.csv").fillna("")
    for r in seed_alias.itertuples():
        if r.herb in known and r.alias != r.herb:
            alias_rows[r.alias] = (r.herb, r.processing, r.note)
    # b) 常见经典方/炮制品别名
    for a, h, proc, note in EXTRA_ALIASES:
        if h in known and a != h and a not in alias_rows:
            # 若 a 本身已是标准药材，不覆写（除非像 犀角->水牛角 或 杏仁 这类不在标准名或明确替代）
            if a not in known or a in {"犀角", "大戟", "川牛膝"}:
                alias_rows[a] = (h, proc, note)
    # c) SymMap SMHB 的 Alias 字段
    for r in smhb.itertuples():
        h = str(r.Chinese_name).strip()
        if h not in known or pd.isna(r.Alias):
            continue
        for a in re.split(r"[,，;；、|]+", str(r.Alias)):
            a = a.strip()
